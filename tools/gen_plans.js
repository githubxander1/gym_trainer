// 生成 data/plans.js，所有 exId 均按中文名从 exercises.json 解析。
// 用法：node tools/gen_plans.js
const fs = require('fs');
const path = require('path');
const data = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'data', 'exercises.json'), 'utf8'));

const byZh = {};
data.forEach((x) => { if (x.nameZh) byZh[x.nameZh] = x.id; });
function id(name) {
  if (byZh[name]) return byZh[name];
  const hit = data.find((x) => x.nameZh && x.nameZh.includes(name));
  return hit ? hit.id : null;
}

// 主项（真实动作）：ex(name, sets, mode, val, rest, options?)
// options.useId：强制绑定某个 exId（用于纠正同名/易混动作的配图，例：站姿反向飞鸟用 0380 而非带凳的 0383）
// options.label：覆盖展示名（保留用户习惯叫法，例：仍显示「哑铃反向飞鸟」但配站姿图）
function ex(name, sets, mode, val, rest, options = {}) {
  const { useId, label, ...restOpts } = options;
  const e = useId || id(name);
  if (!e) throw new Error('未找到动作: ' + name);
  if (options.sideMode === 'alternatingSets' && sets % 2) throw new Error('左右轮换动作必须为偶数组: ' + name);
  const rec = data.find((x) => x.id === e);
  const dispLabel = label || (rec && rec.nameZh) || name;
  return { kind: 'exercise', exId: e, label: dispLabel, sets, mode, reps: mode === 'rep' ? val : 12, workSec: mode === 'time' ? val : 30, restSec: rest, ...restOpts };
}
// 拉伸/说明项（可带 exId 或纯文字）
function st(name, desc, dur, exName) {
  const e = exName ? id(exName) : null;
  return { kind: 'stretch', name, desc, dur, exId: e || undefined };
}
// 有氧收尾（跳绳等）：cardio(name, durSec, count, note)
function cardio(name, durSec, count, note) {
  return { kind: 'cardio', name, durSec, count, note };
}

